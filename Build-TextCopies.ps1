# =====================================================================
#  Build-TextCopies.ps1  -  MAKE THE ".txt" VERSIONS OF THE CODE
# ---------------------------------------------------------------------
#  Some environments block .ps1 files.  This script produces:
#    code-as-text\<name>.txt          one text copy per source file
#    Offline-Patcher-AllInOne.txt     everything in one file, in load order,
#                                     ready for:  Invoke-Expression (Get-Content -Raw .\Offline-Patcher-AllInOne.txt)
#  It also normalises every source file to CRLF line endings + UTF-8 with BOM
#  so Notepad, ISE and the console all read them the same way.
#  Run it again after ANY edit to a .ps1 file, otherwise the .txt copies go stale.
# =====================================================================
#Requires -Version 5.1


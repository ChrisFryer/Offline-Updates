$root   = $PSScriptRoot
if (-not $root) { $root = (Get-Location).Path }
$outDir = Join-Path $root 'code-as-text'
New-Item -ItemType Directory -Path $outDir -Force | Out-Null
$utf8Bom = New-Object System.Text.UTF8Encoding($true)

$sources = @(Get-ChildItem -Path (Join-Path $root 'lib') -Filter '*.ps1' | Sort-Object Name)
$sources += Get-Item -Path (Join-Path $root 'Start-OfflinePatcher.ps1')
$sources += Get-Item -Path (Join-Path $root 'Build-TextCopies.ps1')
$sources += Get-Item -Path (Join-Path $root 'Build-Diagrams.ps1')

$all = New-Object System.Text.StringBuilder
[void]$all.AppendLine('# =====================================================================')
[void]$all.AppendLine('#  Offline-Patcher-AllInOne.txt  -  generated by Build-TextCopies.ps1 on ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
[void]$all.AppendLine('#  USAGE:  cd to the tool folder, then in PowerShell 5.1:')
[void]$all.AppendLine('#          Invoke-Expression (Get-Content -Raw .\Offline-Patcher-AllInOne.txt)')
[void]$all.AppendLine('#  The files below are concatenated in load order; nothing else is different.')
[void]$all.AppendLine('# =====================================================================')
[void]$all.AppendLine('$script:AllInOne = $true                    # tells the launcher section not to dot-source \lib')
[void]$all.AppendLine('$script:RootFolder = (Get-Location).Path    # ALWAYS the current folder - a second run after cd must not keep the old root')
[void]$all.AppendLine()

foreach ($file in $sources) {
    $text = [System.IO.File]::ReadAllText($file.FullName)
    $text = $text -replace "`r?`n", "`r`n"                      # CRLF everywhere
    if (-not $text.EndsWith("`r`n")) { $text += "`r`n" }
    [System.IO.File]::WriteAllText($file.FullName, $text, $utf8Bom)   # normalise the source itself

    $txtPath = Join-Path $outDir ($file.BaseName + '.txt')
    [System.IO.File]::WriteAllText($txtPath, $text, $utf8Bom)
    Write-Host ("{0,-28} -> {1}" -f $file.Name, $txtPath)

    if ($file.Name -like 'Build-*.ps1') { continue }   # the build tools are not part of the runtime
    [void]$all.AppendLine()
    [void]$all.AppendLine('# ===================== BEGIN ' + $file.Name + ' =====================')
    [void]$all.Append($text)
    [void]$all.AppendLine('# ===================== END ' + $file.Name + ' =======================')
}

$allPath = Join-Path $root 'Offline-Patcher-AllInOne.txt'
[System.IO.File]::WriteAllText($allPath, $all.ToString(), $utf8Bom)
Write-Host ("All-in-one                   -> {0}  ({1} KB)" -f $allPath, [math]::Round((Get-Item $allPath).Length / 1KB)) -ForegroundColor Green
